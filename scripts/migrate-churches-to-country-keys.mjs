#!/usr/bin/env node
/**
 * Phase 1 data migration: namespace church KV storage by country.
 *
 * WHAT IT DOES
 *   - Rekeys the primary church arrays:  churches:{ST}       -> churches:US:{ST}
 *   - Rekeys the per-state search index:  churches:sidx:{ST}  -> churches:sidx:US:{ST}
 *   - Backfills each church record in those arrays with:
 *        country: "US"   (ISO 3166-1 alpha-2)
 *        region:  "US-{ST}"  (ISO 3166-2)
 *
 * WHAT IT DELIBERATELY DOES NOT DO
 *   - It does NOT change church `id` values (`${ST}-${osmId}`). Those ids are
 *     referenced by homeCampusId, suggestion/enrichment KV keys, and the audit
 *     log; rewriting them would orphan those cross-references. Country-namespaced
 *     ids are only used for NEW countries going forward. The storage-key
 *     namespace + the new `country` field already disambiguate e.g. California
 *     (churches:US:CA) from Canada (churches:CA:*).
 *   - It does NOT migrate related state-scoped families (pending-churches:{ST},
 *     suggestions:*, enrichment:google:{ST}-*, churches:meta, review-stats).
 *     It REPORTS them so their handling can be coordinated with the server
 *     (Phase 2) changes. review-stats caches are regenerated by the server, so
 *     they can simply be recomputed after migration.
 *
 * IMPORTANT SEQUENCING
 *   Executing this rekey makes the OLD keys disappear. The server currently
 *   reads `churches:{ST}`, so DO NOT --execute against a database the live app
 *   points at until the server (Phase 2) reads the new `churches:US:{ST}` keys.
 *   Run it against a backup / non-prod Supabase project first.
 *
 * SAFETY
 *   - Dry-run by DEFAULT: prints a full report and writes nothing.
 *   - Writing requires BOTH the --execute flag AND a service-role key.
 *   - Requires SUPABASE_SERVICE_ROLE_KEY (never the anon key) for table access,
 *     so it cannot touch any database without that secret in the environment.
 *
 * USAGE
 *   Dry run (default, safe):
 *     SUPABASE_SERVICE_ROLE_KEY=... node scripts/migrate-churches-to-country-keys.mjs
 *   Execute against the project the key belongs to (point at a backup first!):
 *     SUPABASE_SERVICE_ROLE_KEY=... node scripts/migrate-churches-to-country-keys.mjs --execute
 *   Override project:
 *     SUPABASE_PROJECT_ID=... SUPABASE_SERVICE_ROLE_KEY=... node scripts/...
 */
import { createClient } from "@supabase/supabase-js";

const TABLE = "kv_store_283d8046";
const COUNTRY = "US";

const PROJECT_ID = process.env.SUPABASE_PROJECT_ID ?? "epufchwxofsyuictfufy";
const SERVICE_ROLE_KEY = process.env.SUPABASE_SERVICE_ROLE_KEY;
const EXECUTE = process.argv.includes("--execute");

// 50 states + DC. Kept local (this is a standalone Node script that must not
// pull the browser/d3 module chain from src/app/config/countries.ts).
const US_STATES = new Set([
  "AL", "AK", "AZ", "AR", "CA", "CO", "CT", "DE", "DC", "FL", "GA", "HI", "ID",
  "IL", "IN", "IA", "KS", "KY", "LA", "ME", "MD", "MA", "MI", "MN", "MS", "MO",
  "MT", "NE", "NV", "NH", "NJ", "NM", "NY", "NC", "ND", "OH", "OK", "OR", "PA",
  "RI", "SC", "SD", "TN", "TX", "UT", "VT", "VA", "WA", "WV", "WI", "WY",
]);

function fail(msg) {
  console.error(`\n✖ ${msg}\n`);
  process.exit(1);
}

if (!SERVICE_ROLE_KEY) {
  fail(
    "SUPABASE_SERVICE_ROLE_KEY is required (the anon key cannot read the KV " +
      "table). Set it in the environment. Without it this script does nothing.",
  );
}

const supabase = createClient(
  `https://${PROJECT_ID}.supabase.co`,
  SERVICE_ROLE_KEY,
  { auth: { persistSession: false } },
);

/** Fetch all rows whose key starts with `churches:` (paged to be safe). */
async function fetchChurchKeys() {
  const rows = [];
  const pageSize = 1000;
  for (let from = 0; ; from += pageSize) {
    const { data, error } = await supabase
      .from(TABLE)
      .select("key, value")
      .like("key", "churches:%")
      .range(from, from + pageSize - 1);
    if (error) fail(`Query failed: ${error.message}`);
    rows.push(...data);
    if (data.length < pageSize) break;
  }
  return rows;
}

/** Classify a `churches:*` key into a migration action. */
function classify(key) {
  // churches:sidx:{ST}
  const sidx = key.match(/^churches:sidx:([A-Z]{2})$/);
  if (sidx && US_STATES.has(sidx[1])) {
    return { kind: "sidx", st: sidx[1], newKey: `churches:sidx:${COUNTRY}:${sidx[1]}` };
  }
  // churches:{ST}  (primary array) — but NOT the already-namespaced or special keys
  const prim = key.match(/^churches:([A-Z]{2})$/);
  if (prim && US_STATES.has(prim[1])) {
    return { kind: "primary", st: prim[1], newKey: `churches:${COUNTRY}:${prim[1]}` };
  }
  // Already namespaced (idempotency): churches:US:{ST} / churches:sidx:US:{ST}
  if (/^churches:[A-Z]{2}:[A-Z]{2}$/.test(key) || /^churches:sidx:[A-Z]{2}:[A-Z]{2}$/.test(key)) {
    return { kind: "already-migrated" };
  }
  // Everything else: meta, review-stats, review-stats:{ST}, etc.
  return { kind: "other" };
}

/** Backfill country/region onto each church record in a primary array value. */
function backfillRecords(value, st) {
  if (!Array.isArray(value)) return { value, changed: 0 };
  let changed = 0;
  const region = `${COUNTRY}-${st}`;
  const next = value.map((ch) => {
    if (ch && typeof ch === "object" && (ch.country !== COUNTRY || ch.region !== region)) {
      changed++;
      return { ...ch, country: COUNTRY, region };
    }
    return ch;
  });
  return { value: next, changed };
}

async function main() {
  console.log(`\nProject:   ${PROJECT_ID}`);
  console.log(`Mode:      ${EXECUTE ? "EXECUTE (will write)" : "DRY RUN (no writes)"}`);
  console.log(`Table:     ${TABLE}\n`);

  const rows = await fetchChurchKeys();
  console.log(`Fetched ${rows.length} key(s) matching "churches:%".\n`);

  const plan = { primary: [], sidx: [], other: [], alreadyMigrated: 0 };
  let totalRecords = 0;
  let recordsToBackfill = 0;

  for (const row of rows) {
    const c = classify(row.key);
    if (c.kind === "primary") {
      const { value, changed } = backfillRecords(row.value, c.st);
      const count = Array.isArray(row.value) ? row.value.length : 0;
      totalRecords += count;
      recordsToBackfill += changed;
      plan.primary.push({ oldKey: row.key, newKey: c.newKey, count, backfill: changed, value });
    } else if (c.kind === "sidx") {
      plan.sidx.push({ oldKey: row.key, newKey: c.newKey, value: row.value });
    } else if (c.kind === "already-migrated") {
      plan.alreadyMigrated++;
    } else {
      plan.other.push(row.key);
    }
  }

  // ── Report ──
  console.log("── Primary church arrays (churches:{ST} -> churches:US:{ST}) ──");
  for (const p of plan.primary.sort((a, b) => a.oldKey.localeCompare(b.oldKey))) {
    console.log(`  ${p.oldKey.padEnd(16)} -> ${p.newKey.padEnd(20)}  ${p.count} churches, ${p.backfill} to backfill`);
  }
  console.log(`\n  ${plan.primary.length} state array(s), ${totalRecords} total churches, ${recordsToBackfill} records need country/region.\n`);

  console.log("── Search indexes (churches:sidx:{ST} -> churches:sidx:US:{ST}) ──");
  for (const s of plan.sidx.sort((a, b) => a.oldKey.localeCompare(b.oldKey))) {
    console.log(`  ${s.oldKey.padEnd(22)} -> ${s.newKey}`);
  }
  console.log(`\n  ${plan.sidx.length} index key(s).\n`);

  if (plan.alreadyMigrated > 0) {
    console.log(`── Already migrated: ${plan.alreadyMigrated} key(s) already country-namespaced (skipped). ──\n`);
  }

  console.log("── NOT migrated by this script (handle in Phase 2 / regenerate) ──");
  const otherFamilies = {};
  for (const k of plan.other) {
    const fam = k.replace(/:[A-Z]{2}$/, ":{ST}").replace(/:[A-Za-z0-9-]+$/, (m) => (/^:[A-Z]{2}$/.test(m) ? m : ":*"));
    otherFamilies[fam] = (otherFamilies[fam] ?? 0) + 1;
  }
  for (const [fam, n] of Object.entries(otherFamilies).sort()) {
    console.log(`  ${fam}  (${n})`);
  }
  console.log("");

  if (!EXECUTE) {
    console.log("DRY RUN complete. No changes written.");
    console.log("Re-run with --execute (and a backup/non-prod SUPABASE_PROJECT_ID) to apply.\n");
    return;
  }

  // ── Execute ──
  console.log("EXECUTING migration (writing new keys, deleting old keys)…\n");
  for (const p of plan.primary) {
    const up = await supabase.from(TABLE).upsert({ key: p.newKey, value: p.value });
    if (up.error) fail(`Write ${p.newKey} failed: ${up.error.message}`);
    const del = await supabase.from(TABLE).delete().eq("key", p.oldKey);
    if (del.error) fail(`Delete ${p.oldKey} failed: ${del.error.message}`);
    console.log(`  ✓ ${p.oldKey} -> ${p.newKey}`);
  }
  for (const s of plan.sidx) {
    const up = await supabase.from(TABLE).upsert({ key: s.newKey, value: s.value });
    if (up.error) fail(`Write ${s.newKey} failed: ${up.error.message}`);
    const del = await supabase.from(TABLE).delete().eq("key", s.oldKey);
    if (del.error) fail(`Delete ${s.oldKey} failed: ${del.error.message}`);
    console.log(`  ✓ ${s.oldKey} -> ${s.newKey}`);
  }
  console.log("\nMigration complete. Remember to recompute review-stats and verify the server reads the new keys.\n");
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
